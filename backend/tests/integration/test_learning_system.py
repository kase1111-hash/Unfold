def run_db(client: TestClient, fn, *args):
    """Run ``await fn(session, *args)`` in a fresh DB session on the app's loop."""

    async def runner():
        async with get_session_context() as session:
            return await fn(session, *args)

    return client.portal.call(runner)


async def _card_rows(session, document_id: str) -> list[FlashcardORM]:
    # Fresh statistics make the planner pick a sequential scan, as autovacuum
    # does mid-run; ordering must not depend on the physical row order.
    await session.execute(text("ANALYZE flashcards"))
    result = await session.execute(
        select(FlashcardORM)
        .where(FlashcardORM.document_id == document_id)
        .order_by(FlashcardORM.created_at)
    )
    return list(result.scalars().all())


async def _make_due(session, card_id: str) -> None:
    """Pretend the card's review date has passed (e.g. a day went by)."""
    await session.execute(
        update(FlashcardORM)
        .where(FlashcardORM.card_id == card_id)
        .values(next_review=datetime.now(timezone.utc) - timedelta(minutes=1))
    )


async def _clear_content(session, doc_id: str) -> None:
    await session.execute(
        update(DocumentORM).where(DocumentORM.doc_id == doc_id).values(content="  ")
    )


def _due_ids(client: TestClient, learning: str, headers: dict) -> list[str]:
    response = client.get(f"{learning}/flashcards/due", headers=headers)
    assert response.status_code == 200
    return [card["card_id"] for card in response.json()["due_cards"]]


