        assert delete.status_code == 404

        # The owner's card is untouched
        own = client.get(f"{learning}/flashcards", headers=auth_headers).json()
        [card] = [c for c in own["flashcards"] if c["card_id"] == card_id]
        assert card["repetitions"] == 0
        assert card["interval_days"] == 0
        assert own["total"] == len(generated_cards)


