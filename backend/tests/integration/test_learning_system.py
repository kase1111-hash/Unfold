class TestSM2Algorithm:
    """Test the SM2 spaced repetition algorithm."""

    def test_sm2_initial_values(self):
        """Test SM2 algorithm with initial values."""
        from app.services.learning.sm2 import SM2Scheduler, ResponseQuality

        scheduler = SM2Scheduler()
        card_id = "test_card_1"

        scheduler.add_card(card_id)
        state = scheduler.review_card(card_id, ResponseQuality.CORRECT_HESITATION)

        assert state.interval >= 1
        assert state.easiness_factor >= 1.3
        assert state.repetitions == 1

    def test_sm2_quality_5_increases_interval(self):
        """Test that quality 5 increases the interval."""
        from app.services.learning.sm2 import SM2Scheduler, ResponseQuality

        scheduler = SM2Scheduler()
        card_id = "test_card_2"

        scheduler.add_card(card_id)
        state1 = scheduler.review_card(card_id, ResponseQuality.PERFECT)
        interval1 = state1.interval

        state2 = scheduler.review_card(card_id, ResponseQuality.PERFECT)
        interval2 = state2.interval

        assert interval2 >= interval1

    def test_sm2_quality_0_resets(self):
        """Test that quality 0 resets the card."""
        from app.services.learning.sm2 import SM2Scheduler, ResponseQuality

        scheduler = SM2Scheduler()
        card_id = "test_card_3"

        scheduler.add_card(card_id)
        scheduler.review_card(card_id, ResponseQuality.PERFECT)
        scheduler.review_card(card_id, ResponseQuality.PERFECT)

        state = scheduler.review_card(card_id, ResponseQuality.BLACKOUT)

        assert state.interval == 1
        assert state.repetitions == 0

    def test_apply_review_on_stored_state(self):
        """apply_review works on any state, e.g. one loaded from the DB."""
        from app.services.learning.sm2 import (
            CardReviewState,
            ResponseQuality,
            apply_review,
        )

        state = CardReviewState(
            card_id="c", easiness_factor=2.5, interval=6, repetitions=2
        )
        apply_review(state, ResponseQuality.CORRECT_HESITATION)

        assert state.interval == 15  # round(6 * 2.5)
        assert state.repetitions == 3
        assert state.total_reviews == 1
        assert state.correct_reviews == 1

    def test_interval_is_capped(self):
        from app.services.learning.sm2 import (
            MAX_INTERVAL_DAYS,
            CardReviewState,
            ResponseQuality,
            apply_review,
        )

        assert MAX_INTERVAL_DAYS == 36500
        # An interval stored before the cap existed is brought back down.
        state = CardReviewState(
            card_id="c", easiness_factor=2.5, interval=2_900_240, repetitions=13
        )
        apply_review(state, ResponseQuality.PERFECT)
        assert state.interval == 36500
        assert state.next_review - datetime.now(timezone.utc) <= timedelta(days=36500)

        # A failed review still resets the card.
        apply_review(state, ResponseQuality.BLACKOUT)
        assert state.interval == 1
        assert state.repetitions == 0

    def test_days_until_due_rounds_up(self):
        """A card due in 23 hours is due in 1 day, not 0."""
        from app.services.learning.sm2 import CardReviewState

        now = datetime.now(timezone.utc)

        def days(delta: timedelta) -> int:
            return CardReviewState(card_id="c", next_review=now + delta).days_until_due

        assert days(timedelta(hours=23)) == 1
        assert days(timedelta(days=6, hours=1)) == 7
        assert days(timedelta(minutes=-1)) == 0
        assert days(timedelta(hours=-25)) == -1


