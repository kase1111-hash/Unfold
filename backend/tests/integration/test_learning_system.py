class TestFlashcardIsolation:
    """Cards are private to the user who made them."""

    def test_other_user_cannot_see_or_touch_cards(
        self,
        client: TestClient,
        learning: str,
        auth_headers: dict,
        other_auth_headers: dict,
        generated_cards: list[dict],
    ):
        card_id = generated_cards[0]["card_id"]

        due = client.get(f"{learning}/flashcards/due", headers=other_auth_headers)
        assert due.json() == {"due_cards": [], "total_due": 0}
        stats = client.get(f"{learning}/flashcards/stats", headers=other_auth_headers)
